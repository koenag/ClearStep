import {test,expect} from '@playwright/test';
import path from 'node:path';

test('complete no-key decision workflow and responsive dashboard',async({page})=>{
 const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto('/');
 await page.getByRole('button',{name:'Load Demo Business',exact:true}).first().click();
 await expect(page.getByText('Recorded revenue',{exact:true})).toBeVisible();
 await expect(page.getByText('FICTIONAL DEMO',{exact:true})).toBeVisible();
 await page.screenshot({path:'test-results/overview-desktop.png',fullPage:true});
 await page.getByRole('button',{name:'Data Sources',exact:true}).click();
 await page.getByLabel('Upload sales CSV').setInputFiles(path.resolve('../demo_data/juniper_sales.csv'));
 await expect(page.getByRole('status').filter({hasText:'Upload complete'})).toBeVisible();
 await page.getByRole('button',{name:/Analyze Decision/}).first().click();
 await page.getByLabel('Decision question').fill('Should I switch coffee bean suppliers?');
 await page.getByRole('button',{name:'Understand question'}).click();
 await expect(page.getByText(/Mode: deterministic fallback/)).toBeVisible();
 await page.getByRole('button',{name:'Calculate scenarios'}).click();
 await expect(page.getByRole('heading',{name:'Switching is projected to save $1,880.00 over 12 months.'})).toBeVisible();
 await page.getByLabel('Proposed unit cost',{exact:true}).fill('9');
 await page.getByRole('button',{name:'Calculate scenarios'}).click();
 await expect(page.getByRole('heading',{name:'Switching is projected to save $3,080.00 over 12 months.'})).toBeVisible();
 await page.getByLabel('Decision title').fill('Browser-tested supplier comparison');
 await page.getByRole('button',{name:'Save decision',exact:true}).click();
 await expect(page.getByRole('heading',{name:'Projected vs. actual'})).toBeVisible();
 await page.getByRole('button',{name:'Decision History',exact:true}).click();
 await page.getByRole('row').filter({hasText:'Browser-tested supplier comparison'}).first().getByRole('button',{name:'Review & track'}).click();
 await page.getByLabel('Actual monthly procurement savings (USD)').fill('275');
 await page.getByRole('button',{name:'Record actual outcome'}).click();
 await expect(page.getByText('Outcome recorded against the original forecast.')).toBeVisible();
 await expect(page.getByRole('cell',{name:'$275',exact:true})).toBeVisible();
 await page.getByLabel('Decision status').selectOption('implemented');
 await expect(page.getByLabel('Decision status')).toHaveValue('implemented');
 await page.getByRole('button',{name:'Host a promotional event'}).click();
 await page.getByRole('button',{name:'Calculate scenarios'}).click();
 await expect(page.getByRole('heading',{name:'The event has a projected net benefit of $332.80 over 12 months.'})).toBeVisible();
 await page.screenshot({path:'test-results/event-desktop.png',fullPage:true});
 await page.getByLabel('Decision title').fill('Browser-tested event');
 await page.getByRole('button',{name:'Save decision',exact:true}).click();
 await page.getByLabel('Actual incremental visits',{exact:true}).fill('110');
 await page.getByLabel('Actual incremental revenue (USD)').fill('990');
 await page.getByLabel('Actual event + staffing costs (USD)').fill('650');
 await page.getByRole('button',{name:'Record actual outcome'}).click();
 await expect(page.getByText('Repeat visits pending',{exact:true})).toBeVisible();
 await page.getByRole('button',{name:'Overview',exact:true}).click();
 await page.setViewportSize({width:390,height:844});
 await page.screenshot({path:'test-results/overview-mobile.png',fullPage:true});
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBeTruthy();
 expect(errors).toEqual([]);
});

test('unsupported questions do not generate analysis',async({page})=>{
 await page.goto('/');
 await page.getByRole('button',{name:'Load Demo Business',exact:true}).first().click();
 await page.getByRole('button',{name:/Analyze Decision/}).first().click();
 await page.getByLabel('Decision question').fill('Should I hire a new employee?');
 await page.getByRole('button',{name:'Understand question'}).click();
 await expect(page.getByText(/This MVP supports switching suppliers and promotional events/)).toBeVisible();
 await expect(page.getByRole('button',{name:'Save decision',exact:true})).toHaveCount(0);
});
